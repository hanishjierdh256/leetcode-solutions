#!/usr/bin/env python3
"""Regenerate the root README.md of a LeetSync repo (progress counts only).

Usage:  python3 scripts/update_readme.py [repo_dir] [output_file]

Counts the "<number>-<slug>/" folders LeetSync created and reads the
difficulty badge from each folder's README.md. No manual upkeep needed.
"""
import re
import sys
from collections import Counter
from datetime import date
from pathlib import Path

USER = "hanishjierdh256"
LEETCODE_PROFILE = "https://leetcode.com/u/hanishjierdh256/"
DIFFS = ["Easy", "Medium", "Hard"]
ICON = {"Easy": "🟢", "Medium": "🟡", "Hard": "🔴"}
FOLDER_RE = re.compile(r"^\d+-.+$")
DIFF_RE = re.compile(r"Difficulty-(Easy|Medium|Hard)")


def difficulty(folder: Path):
    readme = folder / "README.md"
    if not readme.exists():
        return None
    m = DIFF_RE.search(readme.read_text(encoding="utf-8", errors="replace"))
    return m.group(1) if m else None


def build(counts: Counter) -> str:
    total = sum(counts.values())
    rows = "\n".join(f"| {ICON[d]} {d} | {counts.get(d, 0)} |" for d in DIFFS)
    return f"""# LeetCode Solutions

Python solutions to LeetCode problems, synced automatically with [LeetSync](https://github.com/LeetSync/LeetSync). I'm practicing data structures and algorithms to prepare for software development internships. I solve each problem on my own first, then review other solutions and note what I learned.

![Solved](https://img.shields.io/badge/solved-{total}-blue) ![Language](https://img.shields.io/badge/language-Python-3776AB) [![LeetCode](https://img.shields.io/badge/LeetCode-{USER}-FFA116)]({LEETCODE_PROFILE})

## Progress

| Difficulty | Solved |
|---|---|
{rows}
| **Total** | **{total}** |

## How this repo works

Each problem lives in its own folder, `<number>-<slug>/`, created by LeetSync when a submission is accepted. Each folder has the problem statement and my Python solution. The progress table above is generated by [`scripts/update_readme.py`](./scripts/update_readme.py).

## Connect

- GitHub: [{USER}](https://github.com/{USER})
- LeetCode: [{USER}]({LEETCODE_PROFILE})

<sub>Progress last updated {date.today().isoformat()}.</sub>
"""


def main():
    repo = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else repo / "README.md"
    folders = [f for f in repo.iterdir() if f.is_dir() and FOLDER_RE.match(f.name)]
    counts = Counter(d for d in map(difficulty, folders) if d)
    out.write_text(build(counts), encoding="utf-8")
    print(f"{len(folders)} problems, {dict(counts)} -> {out}")


if __name__ == "__main__":
    main()
